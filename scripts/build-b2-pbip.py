    save(MODEL/'definition.pbism',{'$schema':S+'item/semanticModel/definitionProperties/1.0.0/schema.json','version':'4.2','settings':{}})
    write(MODEL/'definition/database.tmdl','database\n\tcompatibilityLevel: 1606')
    names=['Segments','Payments','Age','CreditLimit','Status','Metrics']
    write(MODEL/'definition/model.tmdl','model Model\n\tculture: fr-FR\n\tdefaultPowerBIDataSourceVersion: powerBI_V3\n\tdiscourageImplicitMeasures\n\tsourceQueryCulture: fr-FR\n\n'+'\n'.join('ref table '+n for n in names))
    sf=[('age_band','string'),('credit_limit_band','string'),('september_status','int64'),('client_count','int64'),('default_count','int64'),('delayed_count','int64'),('total_credit_limit_ntd','int64'),('total_age_years','int64')]
    pf=[('age_band','string'),('credit_limit_band','string'),('september_status','int64'),('period','string'),('client_observations','int64'),('delayed_clients','int64')]
    write(MODEL/'definition/tables/Segments.tmdl',table_tmdl('Segments',sf,csv_m('uci350_segments.csv',sf)))
    write(MODEL/'definition/tables/Payments.tmdl',table_tmdl('Payments',pf,csv_m('uci350_payment_months.csv',pf)))
    stat=[('september_status','int64')]
    write(MODEL/'definition/tables/Age.tmdl',dim_tmdl('Age','age_band',
          ['18-29','30-39','40-49','50-59','60+']))
    write(MODEL/'definition/tables/CreditLimit.tmdl',dim_tmdl('CreditLimit','credit_limit_band',
          ['<50k','50k-99k','100k-199k','200k-499k','500k+']))
    write(MODEL/'definition/tables/Status.tmdl',table_tmdl('Status',stat,dim_m(stat,[[i] for i in range(-2,10)])))
    relationships=[]
    for fact in ['Segments','Payments']:
        for dim,col in [('Age','age_band'),('CreditLimit','credit_limit_band'),('Status','september_status')]:
            relationships.extend([f'relationship {fact}_{dim}',f'\tfromColumn: {fact}.{col}',f'\ttoColumn: {dim}.{col}',''])
    write(MODEL/'definition/relationships.tmdl','\n'.join(relationships))
    measures=[('Dossiers','SUM(Segments[client_count])','#,##0','01 Portefeuille'),('Défauts','SUM(Segments[default_count])','#,##0','01 Portefeuille'),('Taux de défaut','DIVIDE([Défauts],[Dossiers])','0.0%','02 Risque'),('Limite crédit totale','SUM(Segments[total_credit_limit_ntd])','#,##0','01 Portefeuille'),('Limite moyenne','DIVIDE([Limite crédit totale],[Dossiers])','#,##0','01 Portefeuille'),('Age moyen','DIVIDE(SUM(Segments[total_age_years]),[Dossiers])','0.0','01 Portefeuille'),('Retards septembre','SUM(Segments[delayed_count])','#,##0','02 Risque'),('Taux retard septembre','DIVIDE([Retards septembre],[Dossiers])','0.0%','02 Risque'),('Observations mensuelles','SUM(Payments[client_observations])','#,##0','03 Historique'),('Clients retard mensuels','SUM(Payments[delayed_clients])','#,##0','03 Historique'),('Taux retard mensuel','DIVIDE([Clients retard mensuels],[Observations mensuelles])','0.0%','03 Historique'),('Contrôle dénominateur','IF(SUMX(ALL(Segments),Segments[client_count])=30000,1,0)','0','04 Qualité'),('Contrôle défauts','IF(SUMX(ALL(Segments),Segments[default_count])=6636,1,0)','0','04 Qualité')]
    ml=['table Metrics','', '\tcolumn MetricKey','\t\tdataType: int64','\t\tisHidden','\t\tsummarizeBy: none','\t\tsourceColumn: MetricKey','']
    for n,dax,formatString,folder in measures:
        ml.extend([f"\tmeasure '{n}' = {dax}",f'\t\tformatString: {formatString}',f'\t\tdisplayFolder: {folder}',''])
    ml.extend(['\tpartition Metrics = m','\t\tmode: import','\t\tsource =','\t\t\tlet','\t\t\t    Source = #table(type table [MetricKey = Int64.Type], {{1}})','\t\t\tin','\t\t\t    Source'])
    write(MODEL/'definition/tables/Metrics.tmdl','\n'.join(ml))
    pages=[('overview','01 · Vue générale'),('risk','02 · Risque de crédit'),('history','03 · Paiements 2005'),('quality','04 · Qualité et méthode')]
    save(REPORT/'definition/pages/pages.json',{'$schema':S+'item/report/definition/pagesMetadata/1.1.0/schema.json','pageOrder':[x for x,_ in pages],'activePageName':'overview'})
    for pid,title in pages:
        p=REPORT/'definition/pages'/pid
        save(p/'page.json',{'$schema':S+'item/report/definition/page/2.1.0/schema.json','name':pid,'displayName':title,'displayOption':'FitToPage','height':720,'width':1280,
            'objects':{'background':item(color=solid(COLOR['bg']),transparency=literal(0)),'outspace':item(color=solid(COLOR['bg']),transparency=literal(0))}})
        # Remove only generated visual definitions so retired panels cannot persist
        # as ghosts when running the generator after a layout revision.
        visual_root=p/'visuals'
        if visual_root.exists():
            shutil.rmtree(visual_root)
        visuals=[]
        def v(key,*a,**kw): visuals.append(make_visual(pid+'_'+key,*a,order=len(visuals)+1,**kw))
        def txt(key,*a,**kw):visuals.append(textbox(pid+'_'+key,*a,order=len(visuals)+1,**kw))
        txt('heading',34,18,1120,54,title,22)
        txt('context',36,77,1165,25,'UCI 350 · Taïwan 2005  |  Limites en NTD  |  Données historiques — aucune décision de crédit',10,COLOR['muted'],'400')
        metric=lambda name:('Metrics',name,True)
        col=lambda t,n:(t,n,False)
        # R2.3 layout: a compact header, KPIs, filter rail, then readable chart / table evidence.
        if pid=='overview':
            for i,(k,t,m) in enumerate([
                ('n','Dossiers','Dossiers'),('d','Défauts observés','Défauts'),
                ('r','Taux de défaut','Taux de défaut'),('a','Limite moyenne NTD','Limite moyenne')
            ]):
                v(k,34+i*307,114,288,110,'card',{'Values':[metric(m)]},t)
            v('ageFilter',34,241,292,78,'slicer',{'Values':[col('Age','age_band')]},'Tranche d’âge')
            v('limitFilter',342,241,333,78,'slicer',{'Values':[col('CreditLimit','credit_limit_band')]},'Limite de crédit')
            txt('note',712,249,508,59,'Base totale UCI : 30 000 dossiers. Les KPI et graphiques reflètent les filtres et les barres sélectionnées.',11,COLOR['muted'],'400')
            v('age',34,337,586,289,'clusteredBarChart',
              {'Category':[col('Age','age_band')],'Y':[metric('Taux de défaut')]},'Taux de défaut · tranche d’âge')
            set_sort(visuals[-1],'Age','age_band')
            v('limit',636,337,610,289,'clusteredColumnChart',
              {'Category':[col('CreditLimit','credit_limit_band')],'Y':[metric('Taux de défaut')]},'Taux de défaut · limite de crédit')
            set_sort(visuals[-1],'CreditLimit','credit_limit_band')
            txt('footer',36,643,1188,39,'LIMIT_BAL est une limite accordée (NTD), pas un encours bancaire.',11,COLOR['muted'],'400')
        elif pid=='risk':
            for i,(k,t,m) in enumerate([
                ('r','Taux de défaut','Taux de défaut'),('d','Défauts','Défauts'),
                ('s','Retards septembre','Retards septembre'),('dr','Taux retard septembre','Taux retard septembre')
            ]):
                v(k,34+i*307,114,288,110,'card',{'Values':[metric(m)]},t)
            v('statusfilter',34,241,314,78,'slicer',{'Values':[col('Status','september_status')]},'Statut de paiement')
            v('agefilter',364,241,300,78,'slicer',{'Values':[col('Age','age_band')]},'Tranche d’âge')
            txt('note',697,248,529,62,'Lecture descriptive des groupes sélectionnés : les KPI changent selon filtres ou clics sur les barres.',10,COLOR['muted'],'400')
            v('status',34,337,545,289,'clusteredColumnChart',
              {'Category':[col('Status','september_status')],'Y':[metric('Taux de défaut')]},'Défaut · code de paiement septembre')
            set_sort(visuals[-1],'Status','september_status')
            v('cohort',595,337,651,289,'tableEx',
              {'Values':[col('CreditLimit','credit_limit_band'),metric('Dossiers'),metric('Défauts'),metric('Taux de défaut')]},
              'Portefeuille · limite de crédit')
            refine_table(visuals[-1],[155,133,130,143],['Limite NTD','Dossiers','Défauts','Taux'])
            set_sort(visuals[-1],'CreditLimit','credit_limit_band')
            txt('footer',36,643,1188,39,'Codes UCI -2, -1, 0, puis 1 à 8 : valeurs historiques, pas un score de risque.',11,COLOR['muted'],'400')
        elif pid=='history':
            for i,(k,t,m) in enumerate([
                ('obs','Observations de paiement','Observations mensuelles'),
                ('del','Paiements en retard','Clients retard mensuels'),
                ('rat','Part en retard','Taux retard mensuel')
            ]):
                v(k,34+i*409,114,391,110,'card',{'Values':[metric(m)]},t)
            v('agefilter',34,241,290,78,'slicer',{'Values':[col('Age','age_band')]},'Tranche d’âge')
            v('limitfilter',340,241,335,78,'slicer',{'Values':[col('CreditLimit','credit_limit_band')]},'Limite de crédit')
            txt('caveat',697,245,532,63,'Six observations des MÊMES clients : la courbe suit les retards, pas une évolution du taux de défaut.',10,COLOR['muted'],'400')
            v('line',34,337,566,289,'lineChart',
              {'Category':[col('Payments','period')],'Y':[metric('Taux retard mensuel')]},'Paiements en retard · avril–septembre 2005')
            set_sort(visuals[-1],'Payments','period')
            v('table',616,337,630,289,'tableEx',
              {'Values':[col('Payments','period'),metric('Observations mensuelles'),
                         metric('Clients retard mensuels'),metric('Taux retard mensuel')]},
              'Détail mensuel')
            refine_table(visuals[-1],[116,135,150,142],['Mois','Obs.','En retard','Taux'])
