#!/usr/bin/env python3
"""Deterministic Power BI PBIP / PBIR project generator for BANK 360 B2.
Sources: public UCI350 aggregates generated by build-b2-aggregates.py.
No Power BI runtime needed for static authoring; Desktop refresh is separate acceptance.
"""
from __future__ import annotations
import json, uuid, re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
BASE=ROOT/'powerbi/BANK-360'
REPORT=BASE/'BANK-360.Report'
MODEL=BASE/'BANK-360.SemanticModel'
S='https://developer.microsoft.com/json-schemas/fabric/'
COLOR={'bg':'#090F1C','surface':'#142034','border':'#2C3E58','fg':'#EAF1F9','muted':'#A6B6CB','gold':'#DAAD54','cyan':'#42B6C7','red':'#E98A83'}
def save(path,data):
    path.parent.mkdir(parents=True,exist_ok=True)
    path.write_text(json.dumps(data,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
def write(path,content):
    path.parent.mkdir(parents=True,exist_ok=True);path.write_text(content.rstrip()+'\n',encoding='utf-8')
def literal(v):
    if isinstance(v,bool):return {'expr':{'Literal':{'Value':'true' if v else 'false'}}}
    if isinstance(v,(int,float)):return {'expr':{'Literal':{'Value':str(v)+'D'}}}
    return {'expr':{'Literal':{'Value':"'"+str(v).replace("'","''")+"'"}}}
def solid(v):return {'solid':{'color':literal(v)}}
def item(**properties):return [{'properties':properties}]
def container(title=None,card=False):
    # Native visual-level container objects.
    x={'background':item(show=literal(True),color=solid(COLOR['surface']),transparency=literal(0)),
       'border':item(show=literal(True),color=solid(COLOR['border']),radius=literal(8)),
       'visualHeader':item(show=literal(False))}
    if title:
        x['title']=item(show=literal(True),text=literal(title),fontSize=literal(12),fontColor=solid(COLOR['fg']),alignment=literal('left'))
    else:x['title']=item(show=literal(False))
    return x
def field(tbl,col,measure=False):
    return {('Measure' if measure else 'Column'):{'Expression':{'SourceRef':{'Entity':tbl}},'Property':col}}
def proj(tbl,col,measure=False):
    return {'field':field(tbl,col,measure),'queryRef':f'{tbl}.{col}','nativeQueryRef':col}
def make_visual(name,x,y,w,h,kind,fields=None,title=None,order=1):
    d={'$schema':S+'item/report/definition/visualContainer/2.11.0/schema.json','name':name,
       'position':{'x':x,'y':y,'z':order,'width':w,'height':h,'tabOrder':order}}
    v={'visualType':kind}
    if fields: v['query']={'queryState':{k:{'projections':[proj(*t) for t in vals]} for k,vals in fields.items()}}
    v['visualContainerObjects']=container(title,kind=='card')
    if kind=='card':
        v['objects']={'labels':item(fontSize=literal(29),color=solid(COLOR['gold']),labelDisplayUnits=literal(1)), 'categoryLabels':item(show=literal(False))}
    elif kind in ('clusteredBarChart','clusteredColumnChart','lineChart'):
        v['objects']={'legend':item(show=literal(False)), 'categoryAxis':item(labelColor=solid(COLOR['muted']),showAxisTitle=literal(False)),
                      'valueAxis':item(labelColor=solid(COLOR['muted']),showAxisTitle=literal(False)),
                      'dataPoint':item(fill=solid(COLOR['cyan']))}
    elif kind=='slicer':
        v['objects']={'general':item(orientation=literal('vertical'))}
    d['visual']=v
    return d
def textbox(name,x,y,w,h,value,fontsize=13,color=None,weight='600',order=1):
    d=make_visual(name,x,y,w,h,'textbox',title=None,order=order)
    d['visual']['objects']={'general':[{'properties':{'paragraphs':[{'textRuns':[{'value':value,'textStyle':{'fontFamily':'Segoe UI','fontSize':str(fontsize)+'pt','fontWeight':weight,'color':color or COLOR['fg']}}]}]}}]}
    d['visual']['visualContainerObjects']={'background':item(show=literal(False)),'border':item(show=literal(False)),'title':item(show=literal(False))}
    return d

def table_tmdl(name,fields,query):
    out=[f'table {name}']
    for col,kind in fields:
        out+=['',f'\tcolumn {col}',f'\t\tdataType: {kind}',f'\t\tsummarizeBy: none',f'\t\tsourceColumn: {col}']
    out+=['',f'\tpartition {name} = m','\t\tmode: import','\t\tsource =']
    out.extend('\t\t\t'+s for s in query.split('\n'))
    out+=['','\tannotation PBI_ResultType = Table']
    return '\n'.join(out)

def csv_m(file,fields):
    typed=', '.join('{"'+k+'", '+('type text' if ty=='string' else 'Int64.Type')+'}' for k,ty in fields)
    return ('let\n'
        f'    Source = Csv.Document(Web.Contents("https://raw.githubusercontent.com", [RelativePath="sogoyou8/BANK-360/main/powerbi/data/{file}"]), [Delimiter=",", Encoding=65001, QuoteStyle=QuoteStyle.Csv]),\n'
        '    Promoted = Table.PromoteHeaders(Source,[PromoteAllScalars=true]),\n'
        f'    Typed = Table.TransformColumnTypes(Promoted,{{{typed}}},"en-US")\n'
        'in\n    Typed')

def dim_m(columns,rows):
    fmt='\n'.join('        {'+','.join((str(v) if isinstance(v,int) else '"'+v.replace('"','""')+'"') for v in row)+'},' for row in rows).rstrip(',')
    types=', '.join(f'{k} = '+('text' if t=='string' else 'Int64.Type') for k,t in columns)
    return f'let\n    Source = #table(type table [{types}], {{\n{fmt}\n    }})\nin\n    Source'

def generate():
    # Standard PBIP project and its documented PBIR report format.
    save(BASE/'BANK-360.pbip',{'$schema':S+'pbip/pbipProperties/1.0.0/schema.json','version':'1.0','artifacts':[{'report':{'path':'BANK-360.Report'}}],'settings':{'enableAutoRecovery':True}})
    save(REPORT/'definition.pbir',{'$schema':S+'item/report/definitionProperties/2.0.0/schema.json','version':'4.0','datasetReference':{'byPath':{'path':'../BANK-360.SemanticModel'}}})
    save(REPORT/'definition/version.json',{'$schema':S+'item/report/definition/versionMetadata/1.0.0/schema.json','version':'2.0.0'})
    save(REPORT/'definition/report.json',{'$schema':S+'item/report/definition/report/3.3.0/schema.json','settings':{'exportDataMode':'AllowSummarized','useEnhancedTooltips':True}})
    save(MODEL/'definition.pbism',{'$schema':S+'item/semanticModel/definitionProperties/1.0.0/schema.json','version':'4.2','settings':{}})
    write(MODEL/'definition/database.tmdl','database\n\tcompatibilityLevel: 1606')
    names=['Segments','Payments','Age','CreditLimit','Status','Metrics']
    write(MODEL/'definition/model.tmdl','model Model\n\tculture: fr-FR\n\tdefaultPowerBIDataSourceVersion: powerBI_V3\n\tdiscourageImplicitMeasures\n\tsourceQueryCulture: fr-FR\n\n'+'\n'.join('ref table '+n for n in names))
    sf=[('age_band','string'),('credit_limit_band','string'),('september_status','int64'),('client_count','int64'),('default_count','int64'),('delayed_count','int64'),('total_credit_limit_ntd','int64'),('total_age_years','int64')]
    pf=[('age_band','string'),('credit_limit_band','string'),('september_status','int64'),('period','string'),('client_observations','int64'),('delayed_clients','int64')]
    write(MODEL/'definition/tables/Segments.tmdl',table_tmdl('Segments',sf,csv_m('uci350_segments.csv',sf)))
    write(MODEL/'definition/tables/Payments.tmdl',table_tmdl('Payments',pf,csv_m('uci350_payment_months.csv',pf)))
    a=[('age_band','string')];lim=[('credit_limit_band','string')];stat=[('september_status','int64')]
    write(MODEL/'definition/tables/Age.tmdl',table_tmdl('Age',a,dim_m(a,[['18-29'],['30-39'],['40-49'],['50-59'],['60+']])))
    write(MODEL/'definition/tables/CreditLimit.tmdl',table_tmdl('CreditLimit',lim,dim_m(lim,[['<50k'],['50k-99k'],['100k-199k'],['200k-499k'],['500k+']])))
    write(MODEL/'definition/tables/Status.tmdl',table_tmdl('Status',stat,dim_m(stat,[[i] for i in range(-2,10)])))
    relationships=[]
    for fact in ['Segments','Payments']:
        for dim,col in [('Age','age_band'),('CreditLimit','credit_limit_band'),('Status','september_status')]:
            relationships.extend([f'relationship {fact}_{dim}',f'\tfromColumn: {fact}.{col}',f'\ttoColumn: {dim}.{col}',''])
    write(MODEL/'definition/relationships.tmdl','\n'.join(relationships))
    measures=[('Dossiers','SUM(Segments[client_count])','#,##0','01 Portefeuille'),('Défauts','SUM(Segments[default_count])','#,##0','01 Portefeuille'),('Taux de défaut','DIVIDE([Défauts],[Dossiers])','0.0%','02 Risque'),('Limite crédit totale','SUM(Segments[total_credit_limit_ntd])','#,##0','01 Portefeuille'),('Limite moyenne','DIVIDE([Limite crédit totale],[Dossiers])','#,##0','01 Portefeuille'),('Age moyen','DIVIDE(SUM(Segments[total_age_years]),[Dossiers])','0.0','01 Portefeuille'),('Retards septembre','SUM(Segments[delayed_count])','#,##0','02 Risque'),('Taux retard septembre','DIVIDE([Retards septembre],[Dossiers])','0.0%','02 Risque'),('Observations mensuelles','SUM(Payments[client_observations])','#,##0','03 Historique'),('Clients retard mensuels','SUM(Payments[delayed_clients])','#,##0','03 Historique'),('Taux retard mensuel','DIVIDE([Clients retard mensuels],[Observations mensuelles])','0.0%','03 Historique'),('Contrôle dénominateur','IF(CALCULATE([Dossiers], REMOVEFILTERS(Age),REMOVEFILTERS(CreditLimit),REMOVEFILTERS(Status))=30000,1,0)','0','04 Qualité'),('Contrôle défauts','IF(CALCULATE([Défauts], REMOVEFILTERS(Age),REMOVEFILTERS(CreditLimit),REMOVEFILTERS(Status))=6636,1,0)','0','04 Qualité')]
    ml=['table Metrics','', '\tcolumn MetricKey','\t\tdataType: int64','\t\tisHidden','\t\tsummarizeBy: none','\t\tsourceColumn: MetricKey','']
    for n,dax,formatString,folder in measures:
        ml.extend([f"\tmeasure '{n}' = {dax}",f'\t\tformatString: {formatString}',f'\t\tdisplayFolder: {folder}',''])
    ml.extend(['\tpartition Metrics = m','\t\tmode: import','\t\tsource =','\t\t\tlet','\t\t\t    Source = #table(type table [MetricKey = Int64.Type], {{1}})','\t\t\tin','\t\t\t    Source'])
    write(MODEL/'definition/tables/Metrics.tmdl','\n'.join(ml))
    pages=[('overview','01 · Vue générale'),('risk','02 · Risque de crédit'),('history','03 · Paiements 2005'),('quality','04 · Qualité et méthode')]
    save(REPORT/'definition/pages/pages.json',{'$schema':S+'item/report/definition/pagesMetadata/1.1.0/schema.json','pageOrder':[x for x,_ in pages],'activePageName':'overview'})
    for pid,title in pages:
        p=REPORT/'definition/pages'/pid
        save(p/'page.json',{'$schema':S+'item/report/definition/page/2.1.0/schema.json','name':pid,'displayName':title,'displayOption':'FitToPage','height':720,'width':1280,
            'objects':{'background':item(color=solid(COLOR['bg']),transparency=literal(0)),'outspace':item(color=solid(COLOR['bg']),transparency=literal(0))}})
        visuals=[]
        def v(key,*a,**kw): visuals.append(make_visual(pid+'_'+key,*a,order=len(visuals)+1,**kw))
        def txt(key,*a,**kw):visuals.append(textbox(pid+'_'+key,*a,order=len(visuals)+1,**kw))
        txt('heading',34,18,1120,54,title,22)
        txt('context',36,71,1165,34,'UCI 350 · Taïwan 2005  |  Limites en NTD  |  Données historiques — aucune décision de crédit',10,COLOR['muted'],'400')
        metric=lambda name:('Metrics',name,True)
        col=lambda t,n:(t,n,False)
        if pid=='overview':
            for i,(k,t,m) in enumerate([('n','Dossiers','Dossiers'),('d','Défauts observés','Défauts'),('r','Taux de défaut','Taux de défaut'),('a','Limite moyenne NTD','Limite moyenne')]):
                v(k,34+i*307,121,288,118,'card',{'Values':[metric(m)]},t)
            v('age',34,260,600,270,'clusteredBarChart',{'Category':[col('Age','age_band')],'Y':[metric('Taux de défaut')]},'Défaut selon la tranche d’âge')
            v('limit',652,260,594,270,'clusteredColumnChart',{'Category':[col('CreditLimit','credit_limit_band')],'Y':[metric('Taux de défaut')]},'Défaut selon la limite de crédit')
            v('ageFilter',34,549,342,132,'slicer',{'Values':[col('Age','age_band')]},'Tranche d’âge')
            v('limitFilter',394,549,410,132,'slicer',{'Values':[col('CreditLimit','credit_limit_band')]},'Limite de crédit')
            txt('note',832,554,394,109,'Taux pondéré : défauts / dossiers. LIMIT_BAL décrit une limite de crédit, pas un encours bancaire.',10,COLOR['muted'],'400')
        elif pid=='risk':
            for i,(k,t,m) in enumerate([('r','Taux de défaut','Taux de défaut'),('d','Défauts','Défauts'),('s','Retards septembre','Retards septembre'),('dr','Taux retard septembre','Taux retard septembre')]):
                v(k,34+i*307,121,288,116,'card',{'Values':[metric(m)]},t)
            v('status',34,258,772,290,'clusteredColumnChart',{'Category':[col('Status','september_status')],'Y':[metric('Taux de défaut')]},'Défaut par statut de remboursement en septembre')
            v('cohort',827,258,419,290,'tableEx',{'Values':[col('CreditLimit','credit_limit_band'),metric('Dossiers'),metric('Défauts'),metric('Taux de défaut')]},'Ventilation par limite de crédit')
            v('statusfilter',34,565,350,124,'slicer',{'Values':[col('Status','september_status')]},'Code paiement septembre')
            v('agefilter',404,565,360,124,'slicer',{'Values':[col('Age','age_band')]},'Tranche d’âge')
            txt('note',786,576,452,95,'Les codes -2, -1, 0 et 1+ proviennent de la source UCI. Corrélation descriptive, pas score individuel.',10,COLOR['muted'],'400')
        elif pid=='history':
            for i,(k,t,m) in enumerate([('obs','Observations de paiement','Observations mensuelles'),('del','Paiements en retard','Clients retard mensuels'),('rat','Part en retard','Taux retard mensuel')]):
                v(k,34+i*409,121,391,114,'card',{'Values':[metric(m)]},t)
            v('line',34,259,798,290,'lineChart',{'Category':[col('Payments','period')],'Y':[metric('Taux retard mensuel')]},'Part de clients en retard · avril → septembre 2005')
            v('table',852,259,394,290,'tableEx',{'Values':[col('Payments','period'),metric('Observations mensuelles'),metric('Clients retard mensuels'),metric('Taux retard mensuel')]},'Détail par mois')
            v('agefilter',34,566,343,118,'slicer',{'Values':[col('Age','age_band')]},'Tranche d’âge')
            v('limitfilter',394,566,392,118,'slicer',{'Values':[col('CreditLimit','credit_limit_band')]},'Limite de crédit')
            txt('caveat',802,576,437,92,'6 observations mensuelles des MÊMES clients : ce graphique ne mesure pas l’évolution temporelle du taux de défaut.',10,COLOR['muted'],'400')
        else:
            for i,(k,t,m) in enumerate([('all','Dossiers disponibles','Dossiers'),('check1','Contrôle 30 000 = 1','Contrôle dénominateur'),('check2','Contrôle 6 636 = 1','Contrôle défauts')]):
                v(k,34+i*409,121,391,113,'card',{'Values':[metric(m)]},t)
            txt('defn',42,273,1183,246, 'SOURCE  UCI Machine Learning Repository · Default of Credit Card Clients · Yeh (2009)\nLICENCE  CC BY 4.0 · https://doi.org/10.24432/C55S3H\nPÉRIMÈTRE  30 000 clients taïwanais · avril–septembre 2005 · étiquette de défaut le mois suivant\nGRANULARITÉ  agrégats par âge × limite de crédit × statut de paiement\nNE PAS INTERPRÉTER  la somme des limites comme encours ; le taux de défaut comme ratio NPL réglementaire\nFRAUDE / EBA  jeux de données distincts : aucune jointure avec ce modèle',12,COLOR['fg'],'400')
            txt('end',42,562,1180,83,'SOURCE REPRODUCTIBLE : scripts/build-b2-aggregates.py · B1 vérifié par GitHub Actions. Pas de données clients individuelles dans GitHub.',11,COLOR['muted'],'400')
        for z in visuals:save(p/'visuals'/z['name']/'visual.json',z)
    print(f'Generated PBIP at {BASE} with {len(pages)} pages, {len(measures)} measures and 3 shared dimensions')
if __name__=='__main__':generate()
